#pragma once

#include <cstdint>
#include <string>
#include <utility>
#include <vector>

#include "ego_planner/math_types.hpp"

namespace ego_planner {

struct GridMapConfig {
  double resolution_m{0.05};
  Vec3 lo_ned{-3.05, -3.05, -3.05};
  Vec3 hi_ned{3.05, 3.05, 0.00};
  double prior_occ_threshold_m{0.038};
  float l_prior_occ{1.10f};
  float l_prior_free{-0.85f};
  float l_free{0.65f};
  float l_occ{1.15f};
  float l_min{-3.0f};
  float l_max{3.5f};
  double arena_half_m{2.99};
  double wall_top_m{1.7272};
};

class GridMap {
 public:
  explicit GridMap(const GridMapConfig& cfg = GridMapConfig{});

  // Load binary prior generated by export_arena_prior.py
  bool loadPriorBinary(const std::string& bin_path);

  // Reset live map back to the loaded arena prior
  void resetToPrior();

  // Raycast a normalized depth image (H x W, row-major float32 in [0, 1], z-depth / far_clip)
  // and fuse into log-odds occupancy, updating the 3D ESDF if occupancy changes.
  void updateFromDepth(const float* depth_norm, int width, int height,
                       double hfov_deg, double vfov_deg, double far_clip,
                       const Vec3& pos_ned, const Quat& q_wxyz, int stride = 4);

  // Force full 3D Euclidean Distance Transform recomputation from current log_odds_
  void recomputeESDF();

  // Voxel index helpers
  bool inBounds(int ix, int iy, int iz) const {
    return ix >= 0 && ix < nx_ && iy >= 0 && iy < ny_ && iz >= 0 && iz < nz_;
  }
  int flatIndex(int ix, int iy, int iz) const {
    return (ix * ny_ + iy) * nz_ + iz;
  }
  Vec3 indexToPos(int ix, int iy, int iz) const {
    return {cfg_.lo_ned.x + ix * cfg_.resolution_m,
            cfg_.lo_ned.y + iy * cfg_.resolution_m,
            cfg_.lo_ned.z + iz * cfg_.resolution_m};
  }
  void posToIndex(const Vec3& p, int& ix, int& iy, int& iz) const {
    ix = std::clamp(static_cast<int>(std::llround((p.x - cfg_.lo_ned.x) / cfg_.resolution_m)), 0, nx_ - 1);
    iy = std::clamp(static_cast<int>(std::llround((p.y - cfg_.lo_ned.y) / cfg_.resolution_m)), 0, ny_ - 1);
    iz = std::clamp(static_cast<int>(std::llround((p.z - cfg_.lo_ned.z) / cfg_.resolution_m)), 0, nz_ - 1);
  }

  // Raw voxel distance (metres)
  double voxelDistance(int ix, int iy, int iz) const {
    if (!inBounds(ix, iy, iz)) return 0.0;
    return static_cast<double>(esdf_[flatIndex(ix, iy, iz)]);
  }

  bool isOccupied(int ix, int iy, int iz) const {
    if (!inBounds(ix, iy, iz)) return true;
    return log_odds_[flatIndex(ix, iy, iz)] >= 0.0f;
  }

  // Trilinearly interpolated obstacle distance at p_ned (metres)
  double getDistance(const Vec3& p_ned) const;

  // Trilinearly interpolated obstacle distance AND analytical gradient d(dist)/dp at p_ned
  double getDistanceAndGradient(const Vec3& p_ned, Vec3& grad_out) const;

  // Collision query for point sample (e.g. RRT* node validity)
  bool isCollisionFree(const Vec3& p_ned, double radius_m = 0.20) const {
    return getDistance(p_ned) >= radius_m;
  }

  // Smooth obstacle cost for trajectory optimization & MPPI rollouts:
  // c(p) = 0.5 * (d - d_safe)^2 if d < d_safe else 0.0
  double getObstacleCost(const Vec3& p_ned, double safe_dist_m = 0.30) const {
    double d = getDistance(p_ned);
    if (d < safe_dist_m) {
      double diff = safe_dist_m - d;
      return 0.5 * diff * diff;
    }
    return 0.0;
  }

  // Check if line segment [a, b] maintains at least min_clearance_m everywhere (e.g. RRT* edge steer)
  bool isSegmentClear(const Vec3& a_ned, const Vec3& b_ned, double min_clearance_m, double step_m = 0.03) const;

  // Dynamically refine a gate's crossing center (N, E, Z) using the live ESDF to handle shifted walls/windows
  Vec3 refineGateCenter(const GateSpec& gate, double margin_from_posts_m = 0.24) const;

  int nx() const { return nx_; }
  int ny() const { return ny_; }
  int nz() const { return nz_; }
  double resolution() const { return cfg_.resolution_m; }
  const GridMapConfig& config() const { return cfg_; }
  int liveUpdatesCount() const { return live_updates_; }

 private:
  GridMapConfig cfg_;
  int nx_{0};
  int ny_{0};
  int nz_{0};
  std::vector<float> prior_dist_;
  std::vector<float> prior_log_odds_;
  std::vector<float> log_odds_;
  std::vector<float> esdf_;
  bool prior_loaded_{false};
  int live_updates_{0};
};

}  // namespace ego_planner

#!/usr/bin/env python3
"""Build the SITL airframe (a PX4 init.d-posix airframe file) from the drone's parameters.

    params.py --fleet <skybeta>/px4/params [--dump drone17.params] --overrides sitl/px4_params.txt --out <airframe>

Layers, later wins:
  1. fleet   skybeta's staged parameter files that every drone gets on top of the baseline (FLEET_FILES below):
             height reference, EKF2 vision, no optical flow, autonomy takeover, UXRCE participant config.
  2. dump    optional: a QGC/MAVProxy dump of the real drone (tab-separated `1 1 NAME VALUE TYPE`, as in
             skybeta/px4/params/fleet/*.params). Only DUMP_ALLOW families are taken, minus DUMP_DENY: the estimator,
             failsafe, navigation and envelope settings. Never the airframe-specific ones (rate/attitude gains, mixer
             geometry, hover thrust, calibration, serial ports, RC mapping): those are tuned for the real airframe and
             would make the x500 dynamics fly wrong or not at all.
  3. overrides  sitl/px4_params.txt: what SITL must differ in (no RC transmitter, ...). Each line `NAME VALUE  # why`.

The output sources PX4's 4001_gz_x500 airframe first (x500 mixer, hover thrust, gz_bridge), then `param set-default`s
each value. rig_entry.sh deletes parameters.bson on every start, so these defaults are what PX4 runs with.
"""
import argparse
import os
import re
import sys

# skybeta/px4/params files applied to every drone after 00_baseline (skybeta CLAUDE.md "Target PX4 parameter sets").
# 01 (MAVLink on TELEM2), 05/06 (RC switches/calibration, board rotation) and 07 (real rotor geometry) describe hardware
# SITL does not have; 04's COM_RC_IN_MODE=0 is replaced by an override (no transmitter), FD_FAIL_R is kept.
FLEET_FILES = ['02_telem2_uxrce_dds.params', '03a_height_reference.params', '03b_ekf2_vision.params',
               '04_rc_only_fd_roll_off.params', '08_no_optical_flow.params', '09_autonomy_takeover.params']
FLEET_DENY = {'MAV_1_CONFIG', 'UXRCE_DDS_CFG', 'SER_TEL2_BAUD', 'SENS_EN_PMW3901', 'SENS_TFLOW_CFG'}  # serial-port params

DUMP_ALLOW = ('EKF2_', 'COM_', 'NAV_', 'MPC_', 'MIS_', 'LNDMC_', 'GF_', 'FD_', 'UXRCE_DDS_PTCFG', 'UXRCE_DDS_SYNCT')
DUMP_DENY = re.compile(r'^(MPC_THR_(HOVER|MIN|MAX)|MPC_USE_HTE|EKF2_(IMU|GPS|RNG|OF|EV)_POS_[XYZ]|EKF2_MAG_.*|'
                       r'COM_RC_IN_MODE|COM_FLTMODE.*|COM_ARM_MAG.*|COM_CPU_MAX|COM_POWER_COUNT|COM_DL_LOSS_T|'
                       r'NAV_DLL_ACT|EKF2_GPS_.*|EKF2_REQ_.*)$')

LINE = re.compile(r'^\s*\d+\s+\d+\s+([A-Z0-9_]+)\s+(\S+)\s+(\d+)\s*$')


def read_params(path):
    """QGC tab format -> {name: value-string}. Comment and blank lines are skipped."""
    out = {}
    with open(path, encoding='utf-8') as f:
        for raw in f:
            if raw.lstrip().startswith('#') or not raw.strip():
                continue
            m = LINE.match(raw)
            if not m:
                raise ValueError(f'{path}: unparsable line: {raw.rstrip()!r}')
            name, value, ptype = m.group(1), m.group(2), int(m.group(3))
            out[name] = fmt(value, ptype)
    return out


def fmt(value, ptype):
    """MAV_PARAM_TYPE 9 = REAL32 keeps its decimals; 1..8 are integers ('6' INT32 may still be written '1.0')."""
    if ptype == 9:
        return repr(float(value))
    return str(int(float(value)))


def read_overrides(path):
    out = {}
    with open(path, encoding='utf-8') as f:
        for n, raw in enumerate(f, 1):
            line = raw.split('#', 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) != 2 or not re.fullmatch(r'[A-Z0-9_]+', parts[0]):
                raise ValueError(f'{path}:{n}: expected `NAME VALUE`, got {raw.rstrip()!r}')
            out[parts[0]] = parts[1]
    return out


def build(fleet_dir, dump, overrides, base='4001_gz_x500'):
    layers = []
    fleet = {}
    for name in FLEET_FILES:
        for k, v in read_params(os.path.join(fleet_dir, name)).items():
            if k not in FLEET_DENY:
                fleet[k] = v
    layers.append(('skybeta fleet files: ' + ', '.join(FLEET_FILES), fleet))
    if dump:
        d = {k: v for k, v in read_params(dump).items() if k.startswith(DUMP_ALLOW) and not DUMP_DENY.match(k)}
        layers.append((f'drone dump {os.path.basename(dump)} (allowlisted families)', d))
    layers.append((f'SITL overrides {os.path.basename(overrides)}', read_overrides(overrides)))

    merged, origin = {}, {}
    for label, values in layers:
        for k, v in values.items():
            merged[k], origin[k] = v, label
    lines = ['#!/bin/sh', '#', '# @name Gazebo x500 skybeta (generated by sitl/params.py: do not edit)', '#',
             '# @type Quadrotor', '#', '',
             '# rig_entry.sh spawns the model itself and sets PX4_GZ_MODEL_NAME, so gz_bridge attaches to it',
             'PX4_SIM_MODEL=${PX4_SIM_MODEL:=gz_x500_skybeta}', f'. ${{R}}etc/init.d-posix/airframes/{base}', '']
    for label, _ in layers:
        lines.append(f'# --- {label}')
        lines += [f'param set-default {k} {merged[k]}' for k in sorted(merged) if origin[k] == label]
        lines.append('')
    return '\n'.join(lines), merged


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--fleet', required=True, help='skybeta/px4/params')
    ap.add_argument('--dump', default='', help='optional drone parameter dump')
    ap.add_argument('--overrides', required=True)
    ap.add_argument('--out', required=True, help='airframe file to write (e.g. .../airframes/4090_gz_x500_skybeta)')
    a = ap.parse_args(argv)
    text, merged = build(a.fleet, a.dump or None, a.overrides)
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'params: {len(merged)} set-defaults -> {a.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())

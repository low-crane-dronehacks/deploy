#!/usr/bin/env python3
"""Texture the Gazebo course in a run's world dir (sitl/run_native.sh calls it; TEXTURES=0 skips it).

    python3 sitl/texture_world.py RUN_WORLD_DIR

Reads RUN_WORLD_DIR/{course.obj, course_faces.npz, net.obj, dronehacks.sdf, textures/}, writes per-material VISUAL
meshes with texture coordinates (vis_*.obj) and rewrites dronehacks.sdf to draw them. Collision is untouched: the
course and net keep their original collision meshes and the ground keeps its collision plane.

  walls + tunnel  textures/walls.jpg (orange)          window panel  textures/window.jpg (light blue)
  floor           textures/carpet.jpg (grey carpet)    net           textures/net.png (faint black, see-through)
  boulders        textures/boulder.jpg (grey stone)    paint         plain off-white (floor markings)
  hall            textures/hall.jpg (cinder block): walls at +-7 m + ceiling, seen through the nets (else empty sky)

Texture coordinates: box projection per triangle (the two world axes across its dominant normal axis), in metres
divided by each material's tile size, so the texture keeps its scale on every surface. The window is the wall
group's diagonal panel along config/arena_prior.json's window line (it is not its own group in the course mesh).
Why: the untextured course gave cuVSLAM almost nothing to track (2026-11-08 SITL takeoffs lost tracking).
"""
from __future__ import annotations

import os
import sys
import xml.etree.ElementTree as ET

import numpy as np

# tile size (m per texture repeat), texture, double-sided
MATERIALS = {
    'walls': (0.75, 'textures/walls.jpg', False),   # short repeat: detail when ~0.5 m from a wall
    'window': (0.8, 'textures/window.jpg', True),
    'floor': (1.0, 'textures/carpet.jpg', False),
    'net': (0.04, 'textures/net.png', True),
    'boulder': (0.6, 'textures/boulder.jpg', False),
    'hall': (1.6, 'textures/hall.jpg', True),
}
# window line (ENU x = E, y = N), from arena_prior.json gate "window": A_ned (-2.7015, -0.6273), B_ned (-1.8423, -0.3146)
WIN_A = np.array([-0.6273, -2.7015])
WIN_B = np.array([-0.3146, -1.8423])
WIN_HALF_THICK = 0.08          # the panel is a few cm thick; faces within this of the line
WIN_N_RANGE = (-3.10, -1.45)   # along the line (N), the panel's extent incl. its end caps
FLOOR_HALF = 15.0              # carpet quad half-size (m): the cameras see the floor through the nets
FLOOR_Z = -0.002               # just under the ground plane (z 0) and the paint (0..3.5 mm): no z-fighting
HALL_HALF, HALL_H = 7.0, 4.5   # hall walls at +-7 m, ceiling at 4.5 m: what the cameras see through the nets


def read_obj(path: str):
    V, F = [], []
    for line in open(path):
        if line.startswith('v '):
            V.append(line.split()[1:4])
        elif line.startswith('f '):
            F.append([int(t.split('/')[0]) - 1 for t in line.split()[1:4]])
    return np.array(V, dtype=np.float64), np.array(F, dtype=np.int64)


def face_normals(V, F):
    n = np.cross(V[F[:, 1]] - V[F[:, 0]], V[F[:, 2]] - V[F[:, 0]])
    return n / np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-12)


def write_textured(path: str, V, F, tile: float | None, smooth: bool = False) -> None:
    """OBJ with box-projected UVs per corner (tile=None: no UVs) and flat (per face) or smooth (per vertex) normals."""
    used, Fc = np.unique(F, return_inverse=True)
    Fc = Fc.reshape(F.shape)
    Vc = V[used]
    fn = face_normals(Vc, Fc)
    lines = ['# GENERATED by sitl/texture_world.py (visual only)\n']
    lines += [f'v {x:.5f} {y:.5f} {z:.5f}\n' for x, y, z in Vc]
    if smooth:
        vn = np.zeros_like(Vc)
        area_n = np.cross(Vc[Fc[:, 1]] - Vc[Fc[:, 0]], Vc[Fc[:, 2]] - Vc[Fc[:, 0]])
        for k in range(3):
            np.add.at(vn, Fc[:, k], area_n)
        vn /= np.maximum(np.linalg.norm(vn, axis=1, keepdims=True), 1e-12)
        ni = Fc + 1
    else:
        vn = fn
        ni = np.repeat(np.arange(1, len(Fc) + 1)[:, None], 3, 1)
    lines += [f'vn {x:.4f} {y:.4f} {z:.4f}\n' for x, y, z in vn]
    if tile is None:
        lines += [f'f {a}//{na} {b}//{nb} {c}//{nc}\n' for (a, b, c), (na, nb, nc) in zip(Fc + 1, ni)]
    else:
        axis = np.argmax(np.abs(fn), 1)                       # dominant normal axis -> project on the other two
        other = np.array([[1, 2], [0, 2], [0, 1]])[axis]      # x-facing: (y, z); y-facing: (x, z); z-facing: (x, y)
        P = Vc[Fc]                                            # (F, 3 corners, 3)
        uv = np.stack([np.take_along_axis(P, np.repeat(other[:, None, :1], 3, 1), 2)[..., 0],
                       np.take_along_axis(P, np.repeat(other[:, None, 1:], 3, 1), 2)[..., 0]], -1) / tile
        lines += [f'vt {u:.4f} {v:.4f}\n' for u, v in uv.reshape(-1, 2)]
        ti = np.arange(1, 3 * len(Fc) + 1).reshape(-1, 3)
        lines += [f'f {a}/{ta}/{na} {b}/{tb}/{nb} {c}/{tc}/{nc}\n'
                  for (a, b, c), (ta, tb, tc), (na, nb, nc) in zip(Fc + 1, ti, ni)]
    with open(path, 'w') as fh:
        fh.writelines(lines)


def material_xml(name: str | None, color=(0.92, 0.92, 0.88)) -> ET.Element:
    m = ET.Element('material')
    if name is None:                                          # plain colour (paint)
        for tag in ('ambient', 'diffuse'):
            ET.SubElement(m, tag).text = '%g %g %g 1' % color
        return m
    _, tex, two_sided = MATERIALS[name]
    ET.SubElement(m, 'ambient').text = '1 1 1 1'
    ET.SubElement(m, 'diffuse').text = '1 1 1 1'
    ET.SubElement(m, 'specular').text = '0.05 0.05 0.05 1'
    if two_sided:
        ET.SubElement(m, 'double_sided').text = 'true'
    metal = ET.SubElement(ET.SubElement(m, 'pbr'), 'metal')
    ET.SubElement(metal, 'albedo_map').text = tex
    ET.SubElement(metal, 'roughness').text = '0.9'
    ET.SubElement(metal, 'metalness').text = '0.0'
    return m


def visual(name: str, mesh: str, material: ET.Element, shadows: bool = True) -> ET.Element:
    v = ET.Element('visual', name=name)
    if not shadows:
        ET.SubElement(v, 'cast_shadows').text = 'false'
    ET.SubElement(ET.SubElement(ET.SubElement(v, 'geometry'), 'mesh'), 'uri').text = mesh
    v.append(material)
    return v


def main(world: str) -> None:
    V, F = read_obj(os.path.join(world, 'course.obj'))
    z = np.load(os.path.join(world, 'course_faces.npz'))
    names = [str(n) for n in z['names']]
    group = np.array(names)[z['group']]
    if len(group) != len(F):
        raise SystemExit(f'course_faces.npz has {len(group)} faces, course.obj {len(F)}: re-run sitl/export_world.py')

    fn = face_normals(V, F)
    cen = V[F].mean(1)
    d = (WIN_B - WIN_A) / np.linalg.norm(WIN_B - WIN_A)
    perp = (cen[:, :2] - WIN_A) @ np.array([d[1], -d[0]])
    window = ((group == 'wall') & (np.abs(perp) < WIN_HALF_THICK) & (cen[:, 1] > WIN_N_RANGE[0])
              & (cen[:, 1] < WIN_N_RANGE[1]))
    walls = ((group == 'wall') | (group == 'tunnel')) & ~window
    meshes = {
        'walls': (walls, MATERIALS['walls'][0], False),
        'window': (window, MATERIALS['window'][0], False),
        'boulder': (group == 'boulder', MATERIALS['boulder'][0], True),
        'paint': (group == 'paint', None, False),
    }
    for key, (mask, tile, smooth) in meshes.items():
        write_textured(os.path.join(world, f'vis_{key}.obj'), V, F[mask], tile, smooth)
        print(f'vis_{key}.obj: {int(mask.sum())} faces')

    Vn, Fn = read_obj(os.path.join(world, 'net.obj'))
    nn = face_normals(Vn, Fn)
    keep = ~((np.abs(nn[:, 2]) > 0.9) & (Vn[Fn].mean(1)[:, 2] < 0.05))     # not the net shell's floor
    write_textured(os.path.join(world, 'vis_net.obj'), Vn, Fn[keep], MATERIALS['net'][0])
    print(f'vis_net.obj: {int(keep.sum())} faces')

    h = FLOOR_HALF
    Vf = np.array([[-h, -h, FLOOR_Z], [h, -h, FLOOR_Z], [h, h, FLOOR_Z], [-h, h, FLOOR_Z]])
    write_textured(os.path.join(world, 'vis_floor.obj'), Vf, np.array([[0, 1, 2], [0, 2, 3]]), MATERIALS['floor'][0])

    a, hh = HALL_HALF, HALL_H
    c = np.array([[-a, -a, 0], [a, -a, 0], [a, a, 0], [-a, a, 0], [-a, -a, hh], [a, -a, hh], [a, a, hh], [-a, a, hh]])
    quads = [(0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7), (4, 5, 6, 7)]      # 4 walls + ceiling
    write_textured(os.path.join(world, 'vis_hall.obj'), c,
                   np.array([t for q in quads for t in ((q[0], q[1], q[2]), (q[0], q[2], q[3]))]), MATERIALS['hall'][0])

    sdf_path = os.path.join(world, 'dronehacks.sdf')
    tree = ET.parse(sdf_path)
    w = tree.getroot().find('world')
    models = {m.get('name'): m for m in w.findall('model')}
    for key, link_owner in (('ground', 'ground'), ('course', 'course')):
        link = models[link_owner].find('link')
        for v in link.findall('visual'):
            link.remove(v)
    models['ground'].find('link').append(visual('carpet', 'vis_floor.obj', material_xml('floor')))
    # no shadows: its ceiling would shade the sun
    models['ground'].find('link').append(visual('hall', 'vis_hall.obj', material_xml('hall'), shadows=False))
    course = models['course'].find('link')
    course.append(visual('walls', 'vis_walls.obj', material_xml('walls')))
    course.append(visual('window', 'vis_window.obj', material_xml('window')))
    course.append(visual('boulders', 'vis_boulder.obj', material_xml('boulder')))
    course.append(visual('paint', 'vis_paint.obj', material_xml(None)))
    net = models['net'].find('link')
    for v in net.findall('visual'):
        net.remove(v)
    net.append(visual('netting', 'vis_net.obj', material_xml('net')))
    # room lighting: ambient fill so surfaces the sun grazes (the hall walls, wall faces) are not near-black
    scene = w.find('scene')
    if scene is None:
        scene = ET.Element('scene')
        w.insert(0, scene)
    for tag, val in (('ambient', '0.55 0.55 0.55 1'), ('background', '0.6 0.6 0.6 1')):
        el = scene.find(tag)
        (el if el is not None else ET.SubElement(scene, tag)).text = val
    ET.indent(tree, '  ')
    tree.write(sdf_path, xml_declaration=True, encoding='unicode')
    print(f'textured {sdf_path}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
